import { pianoAudio } from '../audio/synth.js';
import { SheetGeneratorAlgorithm } from '../utils/sheetGenerator.js';
import { SongSearchComponent } from './SongSearch.js';

const SOLFEGE_MAP = {
  'C': 'Do', 'C#': 'Do#', 'Db': 'Reb',
  'D': 'Re', 'D#': 'Re#', 'Eb': 'Mib',
  'E': 'Mi',
  'F': 'Fa', 'F#': 'Fa#', 'Gb': 'Solb',
  'G': 'Sol', 'G#': 'Sol#', 'Ab': 'Lab',
  'A': 'La', 'A#': 'La#', 'Bb': 'Sib',
  'B': 'Si'
};

export class ContinuousSheetMusicComponent {
  constructor({ song, selectedKeys, onNotePlay, t }) {
    this.song = song;
    this.selectedKeys = selectedKeys;
    this.onNotePlay = onNotePlay;
    this.t = t;
    this.notationMode = 'latin'; // 'latin' (Do Re Mi) o 'anglo' (C D E)
    this.activeNoteIndex = null;
  }

  setSong(song) {
    this.song = song;
    this.activeNoteIndex = null;
  }

  setKeys(keys) {
    this.selectedKeys = keys;
  }

  formatNote(noteName) {
    const match = noteName.match(/^([A-G][#b]?)([0-8])$/);
    if (!match) return noteName;
    const [, pitch, octave] = match;

    if (this.notationMode === 'latin') {
      const solfege = SOLFEGE_MAP[pitch] || pitch;
      return `${solfege}${octave}`;
    }
    return `${pitch}${octave}`;
  }

  // Resalta una nota específica cuando la reproduce el reproductor
  highlightNoteIndex(index) {
    this.activeNoteIndex = index;
    const notes = document.querySelectorAll('.flow-note-node');
    notes.forEach((el, i) => {
      if (i === index) {
        el.classList.add('node-playing');
        el.scrollIntoView({ behavior: 'smooth', block: 'nearest', inline: 'center' });
      } else {
        el.classList.remove('node-playing');
      }
    });
  }

  render() {
    const t = this.t;
    const flatNotes = SongSearchComponent.getFlatNotes(this.song);
    
    // Algoritmo: Genera el flujo continuo y adapta automáticamente la canción
    const flowData = SheetGeneratorAlgorithm.generateContinuousFlow(flatNotes, this.selectedKeys);
    
    // Escala horizontal: píxeles por segundo de música para que se vea extendida y cómoda
    const PIXELS_PER_SECOND = 110;
    const canvasWidth = Math.max(900, Math.round(flowData.totalDuration * PIXELS_PER_SECOND) + 120);

    // Generar línea de estela continua en SVG conectando todas las notas consecutivas
    const svgPoints = flowData.items.map(item => {
      const x = Math.round(item.startTime * PIXELS_PER_SECOND) + 50;
      const y = Math.round((item.topPercent / 100) * 290);
      return `${x},${y}`;
    }).join(' ');

    // Calcular marcadores de inicio de cada sección para dibujarlos en la cinta
    const sectionMarkers = [];
    let lastSection = '';
    flowData.items.forEach((item) => {
      const sec = item.section || '';
      if (sec && sec !== lastSection) {
        sectionMarkers.push({ section: sec, startTime: item.startTime });
        lastSection = sec;
      }
    });

    return `
      <section class="card-section continuous-sheet-card" aria-labelledby="flow-sheet-heading">
        <div class="section-header">
          <div style="display: flex; align-items: center; gap: 0.75rem; flex-wrap: wrap;">
            <h2 id="flow-sheet-heading" class="section-title">
              <span>🌊</span>
              <span>${t('continuousFlowTitle')}</span>
            </h2>
            <span class="section-badge">${this.song.title} · ${t('autoGeneratedBadge')}</span>
          </div>

          <div class="sheet-actions-group">
            <!-- Botón blanco para cambiar entre Do-Re-Mi y C-D-E -->
            <button type="button" id="toggle-continuous-notation-btn" class="btn-white btn-sm btn-pill">
              <span>🔤</span>
              <span>${this.notationMode === 'latin' ? 'Do - Re - Mi' : 'C - D - E'}</span>
            </button>
            <button type="button" id="print-continuous-btn" class="btn-white btn-sm btn-pill">
              <span>🖨️</span>
              <span>${t('printSheet')}</span>
            </button>
          </div>
        </div>

        <!-- Explicación intuitiva para el usuario -->
        <p style="font-size: 0.88rem; color: var(--text-white-dim); margin-top: -0.4rem;">
          ${t('continuousFlowHint')}
        </p>

        <!-- LIENZO DE FLUJO CONTINUO SEGUIDO (SIN CORTES NI DIVISIONES ARTIFICIALES) -->
        <div class="continuous-flow-wrapper" id="flow-scroll-container">
          <div class="continuous-flow-canvas" style="width: ${canvasWidth}px; height: 290px;">
            
            <!-- Líneas de referencia tonal horizontales suaves (guía visual de altura) -->
            <div class="flow-tone-guideline" style="top: 20%;"><span>${t('highNotes')}</span></div>
            <div class="flow-tone-guideline" style="top: 50%;"><span>${t('midNotes')}</span></div>
            <div class="flow-tone-guideline" style="top: 78%;"><span>${t('lowNotes')}</span></div>

            <!-- Marcadores de sección (Intro, Verso, Estribillo, Outro...) sobre la cinta -->
            ${sectionMarkers.map(marker => {
              const leftPos = Math.round(marker.startTime * PIXELS_PER_SECOND) + 30;
              return `
                <div class="flow-section-marker" style="left: ${leftPos}px;">
                  <div class="flow-section-label">${marker.section}</div>
                  <div class="flow-section-line"></div>
                </div>
              `;
            }).join('')}

            <!-- Estela continua dorada que conecta todas las notas en orden -->
            <svg class="flow-connections-svg" width="${canvasWidth}" height="290">
              <polyline 
                points="${svgPoints}" 
                fill="none" 
                stroke="rgba(229, 193, 88, 0.45)" 
                stroke-width="3" 
                stroke-linecap="round"
                stroke-linejoin="round"
                stroke-dasharray="6 4"
              />
            </svg>

            <!-- Cápsulas de notas continuas -->
            ${flowData.items.map((item, idx) => {
              const leftPos = Math.round(item.startTime * PIXELS_PER_SECOND) + 30;
              const noteWidth = Math.max(54, Math.min(130, Math.round(item.duration * PIXELS_PER_SECOND * 0.9)));
              const formattedNote = this.formatNote(item.note);

              return `
                <div 
                  class="flow-note-node ${item.isBlack ? 'accidental' : ''} ${item.wasShifted ? 'transposed' : ''} ${item.wasFolded ? 'folded' : ''}"
                  data-note="${item.note}"
                  data-index="${idx}"
                  style="
                    left: ${leftPos}px; 
                    top: ${item.topPercent}%; 
                    width: ${noteWidth}px;
                  "
                  title="${formattedNote} (${item.duration}s)${item.wasFolded ? ' · ' + t('foldedNotesStatus').replace('{count}', '1') : ''} · Clic para escuchar"
                >
                  <span class="node-bullet">${idx + 1}</span>
                  <span class="node-title">${formattedNote}</span>
                  <span class="node-len-bar"></span>
                </div>
              `;
            }).join('')}
          </div>
        </div>

        <!-- Leyenda de secciones detectadas -->
        ${sectionMarkers.length > 1 ? `
        <div class="flow-sections-legend">
          ${sectionMarkers.map(m => `
            <span class="flow-legend-chip">${m.section}</span>
          `).join('')}
        </div>
        ` : ''}

        <!-- Banner informativo del algoritmo -->
        <div class="key-summary-banner" style="margin-top: 0.25rem;">
          <div class="key-summary-text">
            <span>✨ <strong>${t('algorithmStatus')}:</strong> </span>
            <span>${flowData.items.length} ${t('notesCount')} · ${t('continuousMelodyClean')}</span>
          </div>
          <div style="font-size: 0.8rem; color: var(--gold-accent);">
            ${flowData.isCompressed
              ? t('foldedNotesStatus').replace('{count}', flowData.foldedNotesCount)
              : (flowData.octaveShift !== 0 ? `(${flowData.octaveShift > 0 ? '+' : ''}${flowData.octaveShift} Oct)` : '✓ Rango nativo')}
          </div>
        </div>
        <div style="margin-top: 0.5rem; font-size: 0.78rem; opacity: 0.82;">
          ${t('transcriptionSource')}: ${this.song.sourceLabel || t('generatedApproximate')}
        </div>
      </section>
    `;
  }

  attachEvents(container) {
    const toggleBtn = container.querySelector('#toggle-continuous-notation-btn');
    if (toggleBtn) {
      toggleBtn.addEventListener('click', () => {
        this.notationMode = this.notationMode === 'latin' ? 'anglo' : 'latin';
        const event = new CustomEvent('notation-changed');
        window.dispatchEvent(event);
      });
    }

    const printBtn = container.querySelector('#print-continuous-btn');
    if (printBtn) {
      printBtn.addEventListener('click', () => {
        window.print();
      });
    }

    // Clic en cualquier cápsula de nota de la cinta continua
    const notes = container.querySelectorAll('.flow-note-node');
    notes.forEach(el => {
      el.addEventListener('click', () => {
        const note = el.dataset.note;
        const index = parseInt(el.dataset.index, 10);
        if (note) {
          pianoAudio.playNote(note);
          if (this.onNotePlay) {
            this.onNotePlay(note);
          }
          this.highlightNoteIndex(index);
        }
      });
    });
  }
}
